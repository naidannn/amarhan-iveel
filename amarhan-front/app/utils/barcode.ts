/**
 * 107 хэв. Тэмдэгт бүр 6 элемент (3 зурвас + 3 зай) = 11 модуль өргөн.
 * Сүүлийн (STOP) хэв нь 7 элемент, 13 модуль.
 *
 * Хүснэгтийн бүрэн бүтэн байдлыг `assertPatternTable()` шалгана — буруу
 * хуулсан цифр нь чимээгүй уншигдахгүй код гаргах учраас.
 */
const PATTERNS = [
  '212222', '222122', '222221', '121223', '121322', '131222', '122213', '122312',
  '132212', '221213', '221312', '231212', '112232', '122132', '122231', '113222',
  '123122', '123221', '223211', '221132', '221231', '213212', '223112', '312131',
  '311222', '321122', '321221', '312212', '322112', '322211', '212123', '212321',
  '232121', '111323', '131123', '131321', '112313', '132113', '132311', '211313',
  '231113', '231311', '112133', '112331', '132131', '113123', '113321', '133121',
  '313121', '211331', '231131', '213113', '213311', '213131', '311123', '311321',
  '331121', '312113', '312311', '332111', '314111', '221411', '431111', '111224',
  '111422', '121124', '121421', '141122', '141221', '112214', '112412', '122114',
  '122411', '142112', '142211', '241211', '221114', '413111', '241112', '134111',
  '111242', '121142', '121241', '114212', '124112', '124211', '411212', '421112',
  '421211', '212141', '214121', '412121', '111143', '111341', '131141', '114113',
  '114311', '411113', '411311', '113141', '114131', '311141', '411131', '211412',
  '211214', '211232', '2331112',
]

const START_B = 104
const STOP = 106
const CHECKSUM_MODULO = 103

/** Code 128-B нь ASCII 32–126 (зай…тильд) хүрээг кодчилно */
const ASCII_MIN = 32
const ASCII_MAX = 126

export interface Barcode {
  /** Зурвасууд: SVG-д `<rect>` болж зурагдана */
  bars: Array<{ x: number; width: number }>
  /** Нийт өргөн модулиар — SVG viewBox-д хэрэглэнэ */
  totalModules: number
}

/**
 * Хүснэгтийн цифрүүдийг зөв хуулсан эсэхийг шалгана.
 *
 * Code 128-ийн бүх тэмдэгт ЯГ 11 модуль өргөн (STOP нь 13). Нэг цифр буруу
 * бол нийлбэр зөрнө — тиймээс энэ шалгалт хуулбарлалтын алдааг барина.
 */
export function assertPatternTable(): void {
  PATTERNS.forEach((pattern, index) => {
    const sum = [...pattern].reduce((acc, digit) => acc + Number(digit), 0)
    const expected = index === STOP ? 13 : 11
    if (sum !== expected) {
      throw new Error(`Code 128 хэв #${index} буруу: ${sum} модуль, ${expected} байх ёстой`)
    }
  })
}

/**
 * Уншуулах боломжтой эсэхийг шалгана. Ачааны дугаар латин үсэг, тоо, зураасаас
 * бүрддэг тул хэвийн үед үргэлж хүчинтэй — кирилл тэмдэгт орсныг л барина.
 */
export function isEncodable(text: string): boolean {
  return (
    text.length > 0 &&
    [...text].every(ch => {
      const code = ch.charCodeAt(0)
      return code >= ASCII_MIN && code <= ASCII_MAX
    })
  )
}

/**
 * Текстийг Code 128-B зурвас болгоно.
 *
 * @throws кирилл эсвэл кодчилогдохгүй тэмдэгт орвол
 */
export function encodeCode128(text: string): Barcode {
  if (!isEncodable(text)) {
    throw new Error('Зураасан код зөвхөн латин үсэг, тоо, тэмдэгт агуулна')
  }

  const values = [START_B]
  for (const ch of text) {
    values.push(ch.charCodeAt(0) - ASCII_MIN)
  }

  // Хяналтын цифр: START + Σ(утга × дараалал), дараалал 1-ээс эхэлнэ
  let checksum = START_B
  for (let i = 1; i < values.length; i += 1) {
    checksum += values[i]! * i
  }
  values.push(checksum % CHECKSUM_MODULO)
  values.push(STOP)

  // Элементүүд зурвас/зайгаар СОЛИГДОН явна — эхнийх нь үргэлж зурвас
  const bars: Array<{ x: number; width: number }> = []
  let x = 0
  let isBar = true

  // Хэв бүр 6 элементтэй (зурвасаар эхэлж зайгаар дуусна) тул дараагийн хэв
  // автоматаар зурвасаар эхэлнэ. STOP нь 7 элементтэй боловч хамгийн сүүлд
  // тул дараалалд нөлөөлөхгүй.
  for (const value of values) {
    for (const digit of PATTERNS[value]!) {
      const width = Number(digit)
      if (isBar) bars.push({ x, width })
      x += width
      isBar = !isBar
    }
  }

  return { bars, totalModules: x }
}
