'use strict';

const rateLimit = require('express-rate-limit');
const config = require('../config');

/**
 * Хүсэлтийн хязгаарлалт.
 *
 * ⚠ БИЗНЕСИЙН ХЯЗГААРЛАЛТ: §1.4-ийн дагуу карго өдөрт хэдэн зуу, мянган ачаа
 * бүртгэдэг. Салбарын бүх ажилтан НЭГ гадаад IP-аас ханддаг тул IP-д тулгуурласан
 * хязгаар хэт бага байвал ажлын өдрийн дундуур бүх ажилтныг хааж, бүртгэлийн
 * урсгалыг тасалдуулна. Тиймээс глобал хязгаарыг өгөөмөр (default 1,000 / 15 мин)
 * тавьж, ХОРТ ХЭРЭГЛЭЭНИЙ хамгаалалтыг нэвтрэлтийн endpoint-д (`authLimiter`)
 * хатуу байлгав.
 *
 * Phase 9 (хатууруулалт): хэрэглэгч тус бүрээр (`req.user._id`) тоолох, IP-ээр
 * биш — тэр үед `trust proxy` тохиргоог мөн шалгах шаардлагатай.
 */
const globalLimiter = rateLimit({
  windowMs: config.rateLimit.windowMs,
  max: config.rateLimit.max,
  message: {
    success: false,
    message: 'Хүсэлт хэт олон. Хэсэг хугацааны дараа дахин оролдоно уу',
  },
  standardHeaders: true,
  legacyHeaders: false,
  // Тест нь ХЭДЭН ЗУУН хүсэлт явуулдаг. Хязгаарыг тестэд үлдээвэл тестийн
  // дараалал өөрчлөгдөх бүрт санамсаргүй 429 гарч, шалтгааныг олоход хүндрэнэ.
  skip: () => config.env === 'test',
});

/**
 * Нэвтрэх/нууц үг сэргээх endpoint — нууц үг тааварлахаас хамгаална.
 * Энэ хязгаар тестэд ч хүчинтэй байх шаардлагагүй тул мөн алгасана.
 */
const authLimiter = rateLimit({
  windowMs: 15 * 60 * 1000,
  max: 20,
  message: {
    success: false,
    message: 'Нэвтрэх оролдлого хэт олон. Хэсэг хугацааны дараа дахин оролдоно уу',
  },
  standardHeaders: true,
  legacyHeaders: false,
  skip: () => config.env === 'test',
});

/**
 * Нэвтрэхгүйгээр хандах endpoint-ууд (`/v1/public/*`) — Phase 5.
 *
 * ЗААВАЛ тусдаа хязгаартай байх шалтгаан: ачаа хайх нь танилтгүй бөгөөд
 * дугаараар л ажилладаг. Хязгааргүй бол дугаарын орон зайг дараалан
 * туршиж (`ABC0001`, `ABC0002`, …) аль дугаар бодитоор бүртгэлтэйг, улмаар
 * маскласан утасны эхний 4 оронг цуглуулах боломжтой.
 *
 * Ажилтны глобал хязгаараас (1,000) хамаагүй бага: бодит хэрэглэгч ачаагаа
 * минутанд хэдэн арван удаа хайхгүй.
 */
const publicLimiter = rateLimit({
  windowMs: 15 * 60 * 1000,
  max: 120,
  message: {
    success: false,
    message: 'Хайлт хэт олон. Хэсэг хугацааны дараа дахин оролдоно уу',
  },
  standardHeaders: true,
  legacyHeaders: false,
  skip: () => config.env === 'test',
});

/**
 * Харилцагч ӨӨРӨӨ ачаа бүртгүүлэх (BR-46) — Phase 5.
 *
 * ЗААВАЛ хязгаартай байх шалтгаан: урьдчилсан бүртгэл нь ачааны дугаарыг
 * ЭЗЭМШИНЭ (unique index). Хязгааргүй бол хортой хэрэглэгч дугаарын орон
 * зайг дараалан бүртгэж (`SF0001`, `SF0002`, …) бусдын бодит ачаа ирэхэд
 * өөрийн бүртгэлд холбогдох, эсвэл ажилтны бүртгэлийг тасалдуулах боломжтой.
 *
 * Бодит хэрэглэгч 15 минутанд 30 ачаа мэдүүлэхгүй — 30 нь өгөөмөр хязгаар.
 */
const selfRegisterLimiter = rateLimit({
  windowMs: 15 * 60 * 1000,
  max: 30,
  message: {
    success: false,
    message: 'Бүртгэл хэт олон. Хэсэг хугацааны дараа дахин оролдоно уу',
  },
  standardHeaders: true,
  legacyHeaders: false,
  skip: () => config.env === 'test',
});

module.exports = { globalLimiter, authLimiter, publicLimiter, selfRegisterLimiter };
